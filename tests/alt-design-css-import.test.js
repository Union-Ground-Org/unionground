// @vitest-environment node
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { applyRepositoryFloors, prefixClassesInSelector, scopeSelector, transformCss } from "../scripts/alt-design/import-design-css.mjs";

// The design export's stylesheet is imported mechanically
// (scripts/alt-design/import-design-css.mjs). The whole isolation story rests
// on the transform being total: one unprefixed class or custom property and the
// alternate shell starts restyling the production views mounted inside it, or
// the other way round (thirteen of the design's variable names already exist in
// src/sg-tokens.css with other values).
describe("design CSS import transform", () => {
  it("prefixes classes and custom properties, scopes root and element rules, renames keyframes, drops @font-face", () => {
    const css = [
      ":root{--ink:#000;--green:#0e4034}",
      "body{color:var(--ink)}",
      "a:hover{color:var(--green, red)}",
      ".side .t, h2 .accent{x:1}",
      "@font-face{font-family:X;src:url(a.woff2)}",
      "@keyframes pulse{from{opacity:0}to{opacity:1}}",
      ".live-dot{animation:pulse 1s infinite, blink 2s}",
      "@media (min-width:1081px){body{padding-left:10px}.side{display:flex}}",
    ].join("");
    const out = transformCss(css, { sourceName: "test.html", sourceSha256: "abc" });
    expect(out).toContain(".ugalt{--ug-ink:#000;--ug-green:#0e4034}");
    expect(out).toContain(".ugalt{color:var(--ug-ink)}");
    expect(out).toContain(":where(.ugalt) a:hover:where(:not(.ug-legacy *, .ug-legacy-cards *, .ug-signin *)){color:var(--ug-green, red)}");
    expect(out).toContain(".ug-side .ug-t, :where(.ugalt) h2 .ug-accent{x:1}");
    expect(out).not.toContain("@font-face");
    expect(out).toContain("@keyframes ug-pulse");
    expect(out).toContain("animation:ug-pulse 1s infinite, blink 2s");
    expect(out).toContain(".ugalt{padding-left:10px}");
    expect(out).toContain(".ug-side{display:flex}");
    expect(out.startsWith("/* GENERATED by scripts/alt-design/import-design-css.mjs")).toBe(true);
    expect(out).toContain("sha256 abc");
  });

  it("leaves attribute selectors and pseudo-classes alone", () => {
    expect(prefixClassesInSelector('.ev[href$=".pdf"] .t')).toBe('.ug-ev[href$=".pdf"] .ug-t');
    expect(scopeSelector(":focus-visible")).toBe(":focus-visible");
    expect(scopeSelector("*")).toBe(":where(.ugalt) *:where(:not(.ug-legacy *, .ug-legacy-cards *, .ug-signin *))");
    expect(scopeSelector("*::before")).toBe(":where(.ugalt) *:where(:not(.ug-legacy *, .ug-legacy-cards *, .ug-signin *))::before");
    expect(scopeSelector("h2 .ug-accent")).toBe(":where(.ugalt) h2 .ug-accent");
    expect(scopeSelector("body.has-tabbar .x")).toBe(".ugalt.has-tabbar .x");
  });

  it("the committed stylesheet carries no unprefixed class or custom property", () => {
    const css = readFileSync(new URL("../src/alt/styles/design.css", import.meta.url), "utf8")
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .replace(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/g, '""')
      .replace(/url\([^)]*\)/g, "url()");
    const classes = [...css.matchAll(/\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)/g)].map((match) => match[1]);
    const strays = classes.filter((name) => name !== "ugalt" && !name.startsWith("ug-"));
    expect(strays, `unprefixed classes: ${[...new Set(strays)].slice(0, 10).join(", ")}`).toEqual([]);
    const vars = [...css.matchAll(/--([a-zA-Z_][\w-]*)/g)].map((match) => match[1]);
    const strayVars = vars.filter((name) => !name.startsWith("ug-"));
    expect(strayVars, `unprefixed custom properties: ${[...new Set(strayVars)].slice(0, 10).join(", ")}`).toEqual([]);
    expect(css).not.toContain("@font-face");
    expect(classes.length).toBeGreaterThan(500);
  });
});

describe("repository floors in the generated sheet", () => {
  const css = transformCss(
    ".x input{font-size:14.5px}.y{font-size:7px}.z{width:8px;font-size:0}.w:hover{transform:translateY(-1px)}.v:active,.u{scale:.98}",
  );
  it("holds focusable controls at 16px and readable text at 11px, with no font-size: 0", () => {
    expect(css).toContain(".ug-x input{font-size:16px}");
    expect(css).toContain(".ug-y{font-size:11px}");
    expect(css).toContain(".ug-z{width:8px;overflow:hidden}");
    expect(css).not.toMatch(/font-size:\s*0[;}]/);
  });
  it("resets every hover and press transform under prefers-reduced-motion: reduce", () => {
    expect(css).toContain("@media (prefers-reduced-motion:reduce){.ug-w:hover{transform:none}.ug-v:active{scale:none}}");
  });
  it("is exported for reuse", () => {
    expect(typeof applyRepositoryFloors).toBe("function");
  });
});
